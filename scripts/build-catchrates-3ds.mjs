#!/usr/bin/env node
// Builds shared/live/catch3ds.mjs – the species' catch rates of the 3DS games (X/Y, Omega Ruby/Alpha Sapphire,
// Sun/Moon, Ultra Sun/Ultra Moon), which twicable can't read from their ROM like the GB/GBA/DS ones
// (shared/live/romtypes.mjs). Input: PKHeX's personal tables (https://github.com/kwsch/PKHeX, GPL-3.0,
// PKHeX.Core/Resources/byte/personal/personal_xy|ao|sm|uu): one entry per species in National Dex order (the forms
// after them), PersonalInfo6XY 0x40 bytes, PersonalInfo6AO 0x50, PersonalInfo7 0x54, CatchRate at 0x08 in each.
//
//   node scripts/build-catchrates-3ds.mjs <folder with personal_xy, personal_ao, personal_sm, personal_uu>
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/build-catchrates-3ds.mjs <folder with PKHeX personal_xy, _ao, _sm, _uu>');
  process.exit(2);
}
const GAMES = [
  { id: 'xy', file: 'personal_xy', size: 0x40, count: 721 },
  { id: 'oras', file: 'personal_ao', size: 0x50, count: 721 },
  { id: 'sm', file: 'personal_sm', size: 0x54, count: 802 },
  { id: 'usum', file: 'personal_uu', size: 0x54, count: 807 },
];
const lines = [];
for (const g of GAMES) {
  const b = readFileSync(join(dir, g.file));
  const rates = Buffer.alloc(g.count);
  for (let i = 1; i <= g.count; i++) {
    const r = b[i * g.size + 0x08];
    if (!(r >= 1 && r <= 255)) throw new Error(`${g.file}: species ${i} has catch rate ${r}`);
    rates[i - 1] = r;
  }
  lines.push(`  ${g.id}: '${rates.toString('base64')}',`);
}
const out = `// Generated by scripts/build-catchrates-3ds.mjs – do not edit by hand.
// The species' catch rates of the 3DS games by National Dex number (byte n−1 = #n, base64), from PKHeX's personal
// tables (https://github.com/kwsch/PKHeX, GPL-3.0, PKHeX.Core/Resources/byte/personal: CatchRate at 0x08). Omega Ruby/
// Alpha Sapphire lowered Kyogre, Groudon, Dialga, Palkia, Reshiram and Zekrom to 3 and raised Rayquaza to 45; Ultra
// Sun/Ultra Moon gave the Ultra Beasts 45 and Necrozma 255 – hence one table per game.
const TABLES = {
${lines.join('\n')}
};

const decoded = {};
function table(id) {
  if (!(id in decoded)) {
    const s = TABLES[id];
    if (!s) return (decoded[id] = null);
    const bin = typeof atob === 'function' ? atob(s) : Buffer.from(s, 'base64').toString('binary');
    decoded[id] = Uint8Array.from(bin, (c) => c.charCodeAt(0));
  }
  return decoded[id];
}

/** The catch rate of National Dex #\`species\` in the 3DS game \`game\` (addresses.json id: xy, oras, sm, usum) – or null. */
export function catchRate3ds(game, species) {
  const t = table(String(game || '').split('~')[0]);
  return t && Number.isInteger(species) && species >= 1 && species <= t.length ? t[species - 1] : null;
}
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'shared', 'live', 'catch3ds.mjs');
writeFileSync(target, out);
console.log(`wrote ${target}`);
